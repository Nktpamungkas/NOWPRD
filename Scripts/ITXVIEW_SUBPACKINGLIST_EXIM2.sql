DROP VIEW ITXVIEW_SUBPACKINGLIST_EXIM2;
CREATE VIEW ITXVIEW_SUBPACKINGLIST_EXIM2 AS
WITH base_lines AS (
    -- Ambil dulu kombinasi SALESORDERCODE+ORDERLINE yang relevan
    -- HANYA untuk dokumen yang kita cari. Set ini kecil (harusnya
    -- cuma beberapa baris), jadi jadi driver yang murah.
    SELECT DISTINCT
        TRIM(s2.DLVSALORDERLINESALESORDERCODE) AS SO_CODE,
        s2.DLVSALESORDERLINEORDERLINE AS SO_ORDERLINE
    FROM SALESDOCUMENT s
    LEFT JOIN SALESDOCUMENTLINE s2
        ON s.PROVISIONALCODE = s2.SALESDOCUMENTPROVISIONALCODE
    WHERE s.PROVISIONALCODE = 'ESP2600274'
),
lebar_filtered AS (
    -- ITXVIEWLEBAR di-join ke base_lines (kecil) dulu,
    -- bukan langsung ke seluruh SALESORDERLINE lewat s2.
    SELECT i.*
    FROM ITXVIEWLEBAR i
    INNER JOIN base_lines b
        ON i.SALESORDERCODE = b.SO_CODE
        AND i.ORDERLINE = b.SO_ORDERLINE
),
gramasi_filtered AS (
    SELECT i2.*
    FROM ITXVIEWGRAMASI i2
    INNER JOIN base_lines b
        ON i2.SALESORDERCODE = b.SO_CODE
        AND i2.ORDERLINE = b.SO_ORDERLINE
)
SELECT
    DISTINCT
    EXTERNALREFERENCE || trim(ITEM_NO) || NO_ORDER AS DESC_OF_GOODS,
    PROVISIONALCODE,
    PROVISIONALCOUNTERCODE,
    COMPANYCODE,
    PROVISIONALDOCUMENTDATE,
    EXTERNALREFERENCE,
    EXTERNALITEM,
    ITEM_NO,
    LOTCODE,
    NO_ORDER,
    MESSRS_ID,
    CONSIGNEE_ID,
    ITEMTYPEAFICODE,
    DECOSUBCODE01,
    DECOSUBCODE02,
    DECOSUBCODE03,
    DECOSUBCODE04,
    DECOSUBCODE05,
    DECOSUBCODE06,
    DECOSUBCODE07,
    DECOSUBCODE08,
    ITEMDESCRIPTION,
    width_sintex,
    gsm,
    width,
    USERPRIMARYUOMCODE,
    USERSECONDARYUOMCODE,
    BASESECONDARYUOMCODE
FROM
    (
        SELECT
            DISTINCT
            ALLOCATION2.CODE,
            ALLOCATION2.LOTCODE,
            SALESORDER.CODE AS NO_ORDER,
            s.PROVISIONALCODE,
            s.PROVISIONALCOUNTERCODE,
            s.COMPANYCODE,
            s.PROVISIONALDOCUMENTDATE,
            s2.USERPRIMARYUOMCODE,
            s2.USERSECONDARYUOMCODE,
            s2.BASESECONDARYUOMCODE,
            s2.EXTERNALREFERENCE,
            s2.INTERNALREFERENCE,
            s2.EXTERNALITEM,
            CASE
                WHEN s2.EXTERNALITEM <> '' THEN s2.EXTERNALITEM
                ELSE trim(s2.SUBCODE02) || ' ' || trim(s2.SUBCODE03)
            END AS ITEM_NO,
            BUSINESSPARTNER.NUMBERID AS MESSRS_ID,
            ADDRESS.CODE AS CONSIGNEE_ID,
            s2.ITEMTYPEAFICODE,
            s2.ITEMDESCRIPTION,
            ALLOCATION2.DECOSUBCODE01 AS DECOSUBCODE01,
            ALLOCATION2.DECOSUBCODE02 AS DECOSUBCODE02,
            ALLOCATION2.DECOSUBCODE03 AS DECOSUBCODE03,
            ALLOCATION2.DECOSUBCODE04 AS DECOSUBCODE04,
            ALLOCATION2.DECOSUBCODE05 AS DECOSUBCODE05,
            ALLOCATION2.DECOSUBCODE06 AS DECOSUBCODE06,
            ALLOCATION2.DECOSUBCODE07 AS DECOSUBCODE07,
            ALLOCATION2.DECOSUBCODE08 AS DECOSUBCODE08,
            COALESCE(i2.GRAMASI_KFF, i2.GRAMASI_FKF) AS gsm,
            i.LEBAR AS width,
            CASE
                WHEN E3.hasil_cut = 8 THEN E3.ELEMENTSCUT_WIDTHGROSS
                ELSE E2.WIDTHGROSS
            END AS width_sintex,
            ALLOCATION2.ITEMELEMENTCODE
        FROM
            SALESDOCUMENT s
        LEFT JOIN SALESDOCUMENTLINE s2 ON s.PROVISIONALCODE = s2.SALESDOCUMENTPROVISIONALCODE
        LEFT JOIN SALESORDER SALESORDER ON TRIM(s2.DLVSALORDERLINESALESORDERCODE) = TRIM(SALESORDER.CODE)
        LEFT JOIN ADDRESS ADDRESS ON s.DELIVERYPOINTUNIQUEID = ADDRESS.UNIQUEID AND s.DELIVERYPOINTCODE = ADDRESS.CODE
        LEFT JOIN ORDERPARTNER ORDERPARTNER ON s.FNCORDPRNCUSTOMERSUPPLIERCODE = ORDERPARTNER.CUSTOMERSUPPLIERCODE
        LEFT JOIN BUSINESSPARTNER BUSINESSPARTNER ON ORDERPARTNER.ORDERBUSINESSPARTNERNUMBERID = BUSINESSPARTNER.NUMBERID
        LEFT JOIN (
                SELECT
                    *
                FROM
                    ALLOCATION ALLOCATION
                WHERE
                    ALLOCATION.DETAILTYPE = '1'
                    AND ALLOCATION.ORDERCODE IS NOT NULL
            ) ALLOCATION ON s2.SUBCODE01 = ALLOCATION.DECOSUBCODE01
            AND s2.SUBCODE02 = ALLOCATION.DECOSUBCODE02
            AND s2.SUBCODE03 = ALLOCATION.DECOSUBCODE03
            AND s2.SUBCODE04 = ALLOCATION.DECOSUBCODE04
            AND s2.SUBCODE05 = ALLOCATION.DECOSUBCODE05
            AND s2.SUBCODE06 = ALLOCATION.DECOSUBCODE06
            AND s2.SUBCODE07 = ALLOCATION.DECOSUBCODE07
            AND s2.SUBCODE08 = ALLOCATION.DECOSUBCODE08
            AND s2.SALESDOCUMENTPROVISIONALCODE = ALLOCATION.ORDERCODE
            AND s2.ORDERLINE = ALLOCATION.ORDERLINE
        LEFT JOIN (
                SELECT
                    *
                FROM
                    ALLOCATION ALLOCATION2
                WHERE
                    ALLOCATION2.DETAILTYPE = '0'
            ) ALLOCATION2 ON ALLOCATION.CODE = ALLOCATION2.CODE
            AND ALLOCATION.DECOSUBCODE01 = ALLOCATION2.DECOSUBCODE01
            AND ALLOCATION.DECOSUBCODE02 = ALLOCATION2.DECOSUBCODE02
            AND ALLOCATION.DECOSUBCODE03 = ALLOCATION2.DECOSUBCODE03
            AND ALLOCATION.DECOSUBCODE04 = ALLOCATION2.DECOSUBCODE04
            AND ALLOCATION.DECOSUBCODE05 = ALLOCATION2.DECOSUBCODE05
            AND ALLOCATION.DECOSUBCODE06 = ALLOCATION2.DECOSUBCODE06
            AND ALLOCATION.DECOSUBCODE07 = ALLOCATION2.DECOSUBCODE07
            AND ALLOCATION.DECOSUBCODE08 = ALLOCATION2.DECOSUBCODE08
        LEFT JOIN ELEMENTS E ON E.CODE = ALLOCATION.ITEMELEMENTCODE
            AND E.COMPANYCODE = ALLOCATION.COMPANYCODE
            AND E.ITEMTYPECODE = ALLOCATION.ITEMTYPECODE
            AND E.DECOSUBCODE01 = ALLOCATION.DECOSUBCODE01
            AND E.DECOSUBCODE02 = ALLOCATION.DECOSUBCODE02
            AND E.DECOSUBCODE03 = ALLOCATION.DECOSUBCODE03
            AND E.DECOSUBCODE04 = ALLOCATION.DECOSUBCODE04
            AND E.DECOSUBCODE05 = ALLOCATION.DECOSUBCODE05
            AND E.DECOSUBCODE06 = ALLOCATION.DECOSUBCODE06
            AND E.DECOSUBCODE07 = ALLOCATION.DECOSUBCODE07
            AND E.DECOSUBCODE08 = ALLOCATION.DECOSUBCODE08
            AND E.DECOSUBCODE09 = ALLOCATION.DECOSUBCODE09
            AND E.DECOSUBCODE10 = ALLOCATION.DECOSUBCODE10
        LEFT JOIN ELEMENTSINSPECTION E2 ON E2.ELEMENTCODE = E.CODE AND E2.COMPANYCODE = E.COMPANYCODE
        LEFT JOIN (
                SELECT
                    DISTINCT
                    s.ITEMELEMENTCODE AS ELEMENTSCUT,
                    LEFT (i.ITEMELEMENTCODE, 1) AS hasil_cut,
                    E.WIDTHGROSS AS ELEMENTSCUT_WIDTHGROSS,
                    E.WIDTHNET AS ELEMENTSCUT_WIDTHNET,
                    LEFT(s.ITEMELEMENTCODE, 8) AS DEMAND,
                    s.PROJECTCODE,
                    s.LOTCODE,
                    s.COMPANYCODE,
                    i.ITEMELEMENTCODE
                FROM
                    ITXVIEW_CUT_ELEMENT_TRANSACTION i
                LEFT JOIN STOCKTRANSACTION s ON s.TRANSACTIONNUMBER = i.CUTORGTRTRANSACTIONNUMBER
                LEFT JOIN ELEMENTSINSPECTION E ON E.ELEMENTCODE = s.ITEMELEMENTCODE AND E.COMPANYCODE = s.COMPANYCODE
            ) E3 ON E3.ITEMELEMENTCODE = E2.ELEMENTCODE AND E3.COMPANYCODE = E2.COMPANYCODE
        -- >>> Bagian yang berubah: pakai CTE hasil filter, bukan view langsung <<<
        LEFT JOIN lebar_filtered i ON i.SALESORDERCODE = TRIM(s2.DLVSALORDERLINESALESORDERCODE) AND i.ORDERLINE = s2.DLVSALESORDERLINEORDERLINE
        LEFT JOIN gramasi_filtered i2 ON i2.SALESORDERCODE = TRIM(s2.DLVSALORDERLINESALESORDERCODE) AND i2.ORDERLINE = s2.DLVSALESORDERLINEORDERLINE
        -- <<< bug lama: "AND i.ORDERLINE = ..." di join i2 sudah dibenerin jadi i2.ORDERLINE
        WHERE
            ALLOCATION2.ORIGINTRNTRANSACTIONNUMBER IS NULL
--            AND s.PROVISIONALCODE = 'ESP2600274'
    ) t
;