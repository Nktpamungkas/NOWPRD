SELECT DISTINCT 
	s.CODE AS NO_ORDER,
	s2.EXTERNALREFERENCE AS NO_PO,
	'' AS TOTAL_PEMBAYARAN,
	'' AS DATE_PEMBAYARAN,
	'' AS INVOICE
FROM
	SALESORDER s
LEFT JOIN SALESORDERLINE s2 ON s2.SALESORDERCODE = s.CODE
WHERE 
	s.CODE = 'DOM2600131'
	
SELECT
	iin.INVOICE,
	iin.CURR,
	iin.TOTAL
FROM
	SALESDOCUMENTLINE s 
LEFT JOIN ITXVIEW_INVOICE_NOINVOICE iin ON iin.INVOICE = s.SALESDOCUMENTPROVISIONALCODE
WHERE 
	s.EXTERNALREFERENCE = 'B26030508AA-002'
	AND TRIM(s.DOCUMENTTYPETYPE) = '06'
	
	
SELECT * FROM ITXVIEW_INVOICE_NOINVOICE WHERE INVOICE = 'DMU26050082'
